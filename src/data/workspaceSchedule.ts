export const SLOT_MINUTES = 15;
export const SLOT_HEIGHT_PX = 20;
export const DEFAULT_PLACE_DURATION_MINUTES = 60;
export const MIN_DURATION_MINUTES = 15;
export const MIN_DATE_COLUMN_WIDTH_PX = 148;
export const MAX_EDIT_DURATION_MINUTES = 4 * 60;

export const WORKSPACE_SLOT_COUNT =
  (WORKSPACE_END_MINUTES - WORKSPACE_START_MINUTES) / SLOT_MINUTES;
export const WORKSPACE_GRID_HEIGHT_PX = WORKSPACE_SLOT_COUNT * SLOT_HEIGHT_PX;
export const WORKSPACE_HOUR_LABEL_COUNT =
  (WORKSPACE_END_MINUTES - WORKSPACE_START_MINUTES) / 60 + 1;
